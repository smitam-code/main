# --------------------------------------------------
# VALIDATE TEST DATA
# --------------------------------------------------

if "target" not in test_df.columns:

    st.error("The uploaded CSV must contain a target column.")
    st.stop()

# All models use the same feature order.
expected_features = list(
    models["Logistic Regression"].feature_names_in_
)

missing_features = [
    feature for feature in expected_features
    if feature not in test_df.columns
]

extra_features = [
    feature for feature in test_df.columns
    if feature not in expected_features and feature != "target"
]

if missing_features:

    st.error(
        f"Missing required input features: {missing_features}"
    )
    st.stop()

if extra_features:

    st.warning(
        f"Extra columns will be ignored: {extra_features}"
    )

X_test = test_df[expected_features]
y_test = test_df["target"]

if len(test_df) == 0:
    st.error("The uploaded CSV contains no rows.")
    st.stop()

if X_test.isnull().any().any() or y_test.isnull().any():

    st.error(
        "Missing values detected. Please clean the test CSV "
        "before uploading."
    )
    st.stop()

if not all(
    pd.api.types.is_numeric_dtype(X_test[col])
    for col in X_test.columns
):
    st.error("All input features must be numeric.")
    st.stop()

if not np.isfinite(X_test.to_numpy(dtype=float)).all():

    st.error("Input features contain infinite values.")
    st.stop()

if not np.isfinite(
    pd.to_numeric(y_test, errors="coerce").to_numpy(dtype=float)
).all():

    st.error("The target must contain finite numeric labels.")
    st.stop()

if not set(y_test.unique()).issubset(
    set(models["Logistic Regression"].classes_)
):
    st.error(
        "The target contains labels not supported by the trained models."
    )
    st.stop()

st.success(
    f"Test dataset loaded successfully: {len(test_df)} records."
)


