# --------------------------------------------------
# MODEL CONFIGURATION
# --------------------------------------------------

MODEL_FILES = {
    "Logistic Regression": "model/logistic_regression.joblib",
    "Decision Tree": "model/decision_tree.joblib",
    "KNN": "model/knn.joblib",
    "Naive Bayes": "model/naive_bayes.joblib",
    "Support Vector Machine": "model/svm.joblib"
}

@st.cache_resource
def load_models():

    loaded = {}

    for name, path in MODEL_FILES.items():

        if not os.path.exists(path):
            raise FileNotFoundError(
                f"Missing model: {path}. "
                "Run python train_models.py first."
            )

        loaded[name] = joblib.load(path)

    return loaded


# --------------------------------------------------
# METRIC CALCULATION
# --------------------------------------------------

def calculate_metrics(model, X, y):

    predictions = model.predict(X)
    probabilities = model.predict_proba(X)

    classes = model.classes_

    if len(classes) == 2:

        auc = roc_auc_score(
            y,
            probabilities[:, 1]
        )

        precision = precision_score(
            y,
            predictions,
            zero_division=0
        )

        recall = recall_score(
            y,
            predictions,
            zero_division=0
        )

        f1 = f1_score(
            y,
            predictions,
            zero_division=0
        )

    else:

        auc = roc_auc_score(
            y,
            probabilities,
            multi_class="ovr",
            average="weighted",
            labels=classes
        )

        precision = precision_score(
            y, predictions,
            average="weighted",
            zero_division=0
        )

        recall = recall_score(
            y, predictions,
            average="weighted",
            zero_division=0
        )

        f1 = f1_score(
            y, predictions,
            average="weighted",
            zero_division=0
        )

    metrics = {
        "Accuracy": accuracy_score(y, predictions),
        "AUC": auc,
        "Precision": precision,
        "Recall": recall,
        "F1 Score": f1,
        "MCC": matthews_corrcoef(y, predictions)
    }

    return metrics, predictions


